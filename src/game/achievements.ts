/**
 * Achievements — goals that record what you have done, and pay nothing.
 *
 * WHY THESE ARE NOT UPGRADES
 * -------------------------
 * An achievement changes no number you earn. It is a record, not a reward. The
 * entire layer is therefore additive: it cannot affect the economy, and it cannot
 * be worth exploiting, because there is nothing to exploit it for.
 *
 * ONE SOURCE OF TRUTH
 * -------------------
 * Each definition supplies a single `measure(state) -> Decimal` and a `target`.
 * Whether the achievement is met is DERIVED (`measure >= target`) rather than
 * stated separately, and the progress bar reads from the same `measure`.
 *
 * This is the rule learned twice already in this codebase:
 *   - the production meter, which failed three releases because the bar and the
 *     label were computed separately and could disagree;
 *   - the upgrade panel's "why is this locked" text, which had to be generated by
 *     the same function that decides availability.
 *
 * A locked achievement showing "4 / 25" and the achievement unlocking at 5 are
 * then the same fact, stated once. They cannot drift.
 *
 * PRESTIGE SAFETY
 * ---------------
 * Several criteria are destroyed by a reset -- `generators[id].owned` goes to
 * zero, `upgrades.purchased` empties. An achievement keyed only on current state
 * would therefore be *un-earned* by prestiging, which is absurd.
 *
 * So unlocking is MONOTONIC. The store records an id forever the moment it is
 * met and never removes it; the condition only ever decides admission, never
 * revocation. `checkAchievements` is the only writer and it only ever adds.
 *
 * PURE MODULE
 * -----------
 * No import of the store, of settings, or of storage. This is a lookup table plus
 * a predicate, and the balance simulator formats numbers with the same helpers.
 */
import type Decimal from 'break_infinity.js';
import type { GameState } from './types';
import { GENERATOR_IDS } from './types';
import { dec } from './decimal';

export type AchievementId =
  | 'first_hire'
  | 'team_of_5'
  | 'team_of_25'
  | 'first_upgrade'
  | 'ten_upgrades'
  | 'codebase'
  | 'breakeven'
  | 'series_a'
  | 'burn_it'
  | 'debt_100';

export interface AchievementDef {
  id: AchievementId;
  name: string;
  /** Shown once unlocked. */
  description: string;
  icon: string;
  /**
   * Ordering and grouping. Lower comes first; the panel groups on it.
   * 1 = onboarding, 2 = build a team, 3 = scale, 4 = prestige.
   */
  tier: 1 | 2 | 3 | 4;
  /** The value that must be reached. */
  target: Decimal;
  /**
   * Current value, on the same scale as `target`.
   *
   * Returning a Decimal for everything -- including plain counts -- keeps the
   * comparison and the progress bar identical code paths. A count could be a
   * number and a lifetime total a Decimal; unifying them means `measure` can
   * never return a value the progress bar cannot render.
   */
  measure(state: GameState): Decimal;
}

/** How many generators are owned right now, across every type. */
function totalOwned(state: GameState): Decimal {
  let total = 0;
  for (const id of GENERATOR_IDS) total += state.generators[id]?.owned ?? 0;
  return dec(total);
}

