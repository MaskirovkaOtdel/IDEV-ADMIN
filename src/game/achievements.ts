export const ACHIEVEMENTS_BY_ID: Record<AchievementId, AchievementDef> = Object.fromEntries(
  ACHIEVEMENTS.map((a) => [a.id, a])
) as Record<AchievementId, AchievementDef>;

/**
 * The persisted record: id -> epoch ms it was earned.
 *
 * Sparse on purpose. Only earned achievements are stored, so a save carries ten
 * small numbers rather than ten booleans, and a newly added achievement is absent
 * (i.e. locked) in every existing save without a migration step.
 */
export type AchievementRecord = Record<string, number>;

/**
 * Whether an achievement's condition is currently satisfied.
 *
 * Always derived. Never stored, never restated in the definition — see the header.
 */
export function isMet(def: AchievementDef, state: GameState): boolean {
  return def.measure(state).greaterThanOrEqualTo(def.target);
}

/**
 * Progress toward an achievement as a fraction in [0, 1].
 *
 * WHY THE CLAMP BELOW IS NOT TESTED, AND WHY IT IS STILL HERE
 * -----------------------------------------------------------
 * The first line is what actually caps an overshooting milestone: a cash
 * milestone measures 3.79e9 against a 1e9 target, so the ratio is 3.79 -- and
 * `isMet` is already true, so it returns 1 before the ratio is ever computed.
 *
 * That means `Math.min(1, ...)` is UNREACHABLE for any measure where "reached the
 * target" implies "the ratio is at least 1" -- which is every current definition.
 * A test that claims to cover the clamp is actually covering the early return,
 * and it passes whether or not the clamp exists. (Verified: deleting the clamp
 * leaves the suite green.)
 *
 * It is kept as cheap insurance against a future measure that is not monotonic --
 * a capped counter, a ratio that can fall. If that arrives, an unclamped width
 * would stretch its container, and that is a worse bug than one line of dead code.
 */
export function progressFraction(def: AchievementDef, state: GameState): number {
  if (isMet(def, state)) return 1;
  const ratio = def.measure(state).div(def.target);
  if (!isFiniteNumber(ratio.toNumber())) return 0;
  return Math.min(1, Math.max(0, ratio.toNumber()));
}

function isFiniteNumber(n: number): boolean {
  return Number.isFinite(n);
}

/** Current value and target as display strings, e.g. "4 / 25". */
export function progressText(def: AchievementDef, state: GameState): string {
  return `${def.measure(state).toString()} / ${def.target.toString()}`;
}

export interface AchievementCheck {
  /** The record to store: the old one plus anything newly earned. */
  record: AchievementRecord;
  /** Ids newly earned by THIS check. Empty when nothing changed. */
  newlyUnlocked: AchievementId[];
}

/**
 * Fold any newly-met achievements into a record.
 *
 * NEVER REMOVES AN ENTRY. This is what makes an achievement survive a prestige
 * that wipes the very state its criterion reads: the criterion decides admission,
 * and admission is permanent.
 *
 * Returns the SAME object reference when nothing changed, so callers can use
 * identity to avoid re-rendering on every tick.
 */
export function checkAchievements(
  state: GameState,
  existing: AchievementRecord,
  now: number = Date.now()
): AchievementCheck {
  let record = existing;
  const newlyUnlocked: AchievementId[] = [];

  for (const def of ACHIEVEMENTS) {
    // Skip anything already recorded. This single line is what makes unlocking
    // monotonic: an entry, once written, is never revisited and therefore never
    // removed, however the criterion behaves afterwards.
    if (existing[def.id] !== undefined) continue;
    if (!isMet(def, state)) continue;

    // Copy-on-write: ticks run constantly, and allocating a new record each time
    // would invalidate every achievement selector on every frame.
    if (record === existing) record = { ...existing };
    record[def.id] = now;
    newlyUnlocked.push(def.id);
  }

  return { record, newlyUnlocked };
}

export function unlockedCount(record: AchievementRecord): number {
  let n = 0;
  for (const id of Object.keys(record)) {
    if (ACHIEVEMENTS_BY_ID[id as AchievementId]) n++;
  }
  return n;
}

/**
 * Coerce a parsed `achievements` field into a valid record.
 *
 * localStorage is user-writable and survives across versions, so this is hostile
 * input, exactly like `parseSettings`. Three things are rejected:
 *   - ids that no longer exist (a removed achievement must not linger);
 *   - non-numeric or non-finite timestamps (`NaN` would render as "Invalid Date");
 *   - negative timestamps, which can only come from a hand-edited save.
 *
 * An unknown id is dropped rather than preserved. If an achievement is ever
 * removed and later re-added, the player earns it again -- which is the honest
 * outcome, since the record of an achievement that no longer exists is not a fact
 * the game can vouch for.
 */
export function parseAchievementRecord(raw: unknown): AchievementRecord {
  const out: AchievementRecord = {};
  if (!raw || typeof raw !== 'object' || Array.isArray(raw)) return out;
  const source = raw as Record<string, unknown>;
  for (const key of Object.keys(source)) {
    if (!ACHIEVEMENTS_BY_ID[key as AchievementId]) continue;
    const n = Number(source[key]);
    if (!Number.isFinite(n) || n < 0) continue;
    out[key] = n;
  }
  return out;
}

